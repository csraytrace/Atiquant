def f1(a, b1, q, z, c):
    return a * np.exp(-b1 * q) + (z-a) * np.exp(-c*q)

def f2(b2, q1, a, b1, q, z, c):
    #print(f1(a, b1, q1, z, c))
    return f1(a, b1, q1, z, c) * np.exp(b2*(q1-q))

def f3(b2, q1, a, b1, q, z, c, b3, q2):
    return f2(b2, q1, a, b1, q2, z, c) * np.exp(b3 * (q2 - q))

def f4(b2, q1, a, b1, q, z, c, b3, q2, q3, b4):
    #print(f3(b2, q1, a, b1, q3, z, c, b3, q2))
    return f3(b2, q1, a, b1, q3, z, c, b3, q2) * (q/q3)**-b4



